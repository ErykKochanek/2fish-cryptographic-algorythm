def ROL(number, shift, bitLength):
    shift %= bitLength
    maska = (1 << bitLength) - 1
    return ((number << shift) | (number >> (bitLength - shift))) & maska

def ROR(number, shift, bitLength):
    shift %= bitLength
    maska = (1 << bitLength) - 1
    return ((number >> shift) | (number << (bitLength - shift))) & maska



